"""Generate packet offsets and OFL bitmap ROM from the frozen class table."""
import ast
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
RESEARCH=ROOT/'tmp/blue-plate-plate-display/research'
FIELDS=[('VERSION',8),('STATUS',8),('FRAME',32),('EPOCH',32),('GENERATION',32),('TIME',32),
        ('X',11),('Y',10),('W',11),('H',10),('IDS',49),('SCORES',224),('MARGINS',224),('TASK_MS',32)]


def main():
    source=HERE.parent/'char_model/model.py'
    tree=ast.parse(source.read_text(encoding='utf8'))
    classes=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='CLASSES' for t in n.targets))
    glyphs=classes+'未识别 '
    assert len(classes)==65 and len(set(glyphs))==len(glyphs)
    province_count=next(i for i,c in enumerate(classes) if c.isascii())
    digit_start=next(i for i,c in enumerate(classes) if c.isdigit())
    offset=0;fields={};lines=['// Generated by generate_assets.py. Do not hand-edit indices.']
    for name,width in FIELDS:
        fields[name.lower()]=dict(offset=offset,width=width)
        lines.extend([f'`define PD_{name} {offset} +: {width}',f'`define PD_{name}_LSB {offset}'])
        offset+=width
    lines.extend([f'`define PD_BITS {offset}',f'`define PD_PROVINCES {province_count}',f'`define PD_DIGIT_START {digit_start}',f'`define PD_CLASSES {len(classes)}',
        f'`define PD_UNRECOGNIZED {len(classes)}',f'`define PD_BLANK {len(glyphs)-1}',
        '`define PD_OK 8\'d0','`define PD_NO_TARGET 8\'d1','`define PD_REJECT 8\'d2','`define PD_ERROR 8\'d3',
        '`define PD_EXPIRED 8\'d4','`define PD_CONFIG 8\'d5','`define PD_INVALID 8\'d6'])
    (HERE/'plate_defs.vh').write_text('\n'.join(lines)+'\n',encoding='ascii')
    path=RESEARCH/'NotoSansSC.ttf';cmap=TTFont(path).getBestCmap()
    assert all(ord(c) in cmap for c in glyphs)
    font=ImageFont.truetype(str(path),30)
    font.set_variation_by_axes([600])
    words=[];atlas=Image.new('RGB',(12*64,6*76),'#152a40');draw=ImageDraw.Draw(atlas)
    for i,char in enumerate(glyphs):
        tile=Image.new('L',(32,32));d=ImageDraw.Draw(tile)
        l,t,r,b=font.getbbox(char)
        assert r-l<=32 and b-t<=32,(char,(l,t,r,b))
        d.text(((32-(r-l))//2-l,(32-(b-t))//2-t),char,font=font,fill=255)
        mask=tile.point(lambda v:255 if v>=128 else 0)
        if char!=' ':assert mask.getbbox() is not None
        for y in range(32):words.append(sum((1<<(31-x)) for x in range(32) if mask.getpixel((x,y))))
        atlas.paste(mask.resize((64,64),Image.Resampling.NEAREST),(i%12*64,i//12*76))
        draw.text((i%12*64+2,i//12*76+64),str(i),fill='white')
    words.extend([0]*(4096-len(words)))
    (HERE/'plate_font.mem').write_text(''.join(f'{v:08x}\n' for v in words),encoding='ascii')
    (HERE/'FONT-OFL.txt').write_bytes((RESEARCH/'OFL.txt').read_bytes())
    manifest=dict(font_name='Blue Plate Bitmap Subset',license='OFL-1.1',upstream='https://github.com/google/fonts/tree/main/ofl/notosanssc',
        upstream_font_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),class_source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
        classes=classes,glyphs=glyphs,glyph_count=len(glyphs),size=[32,32],font_size=30,weight=600,threshold=128,
        rom_sha256=hashlib.sha256((HERE/'plate_font.mem').read_bytes()).hexdigest(),packet_bits=offset,fields=fields)
    (HERE/'assets.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf8')
    atlas.save(ROOT/'docs/validation/blue-plate/plate-display/font-atlas.png')
    print('Generated',offset,'packet bits,',len(glyphs),'glyphs; all Unicode mappings present.')


if __name__=='__main__':main()
